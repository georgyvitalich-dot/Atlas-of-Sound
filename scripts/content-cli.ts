// import the app's TypeScript data modules exactly as the app does.
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { ERAS } from '../src/data/eras';
import { GENRES } from '../src/data/genres';
import { COUNTRIES } from '../src/data/registry';
import type { Country, LonLat } from '../src/data/types';
import { COMPLETENESS, type Issue, type StateReport, validateCountry } from '../src/data/validation';

/** Where each country's boundaries live on disk (for the city-coordinates check). */
const GEOMETRY: Record<string, { file: string; object: string }> = {
  us: { file: 'node_modules/us-atlas/states-10m.json', object: 'states' },
};

function regionContainsFor(country: Country) {
  const geo = GEOMETRY[country.id];
  if (!geo) return undefined;
  const topo = JSON.parse(readFileSync(geo.file, 'utf8')) as Topology;
  const fc = feature(topo, topo.objects[geo.object] as GeometryCollection) as GeoJSON.FeatureCollection;
  const byKey = new Map(fc.features.map((f) => [String(f.id), f]));
  const featureOf = new Map(country.regions.map((r) => [r.id, byKey.get(r.geoKey)]));
  return (regionId: string, p: LonLat) => {
    const f = featureOf.get(regionId);
    if (!f) return undefined;
    if (geoContains(f, p)) return true;
    // Coastal cities can sit a hair outside simplified coastlines: allow ~5 km.
    const d = 0.05;
    return [[d, 0], [-d, 0], [0, d], [0, -d]].some(([x, y]) => geoContains(f, [p[0] + x, p[1] + y]));
  };
}

const color = (code: number) => (s: string) => (process.stdout.isTTY ? `\x1b[${code}m${s}\x1b[0m` : s);
const red = color(31), yellow = color(33), green = color(32), dim = color(2), bold = color(1);

function printIssues(issues: Issue[], showInfo: boolean) {
  const order = { error: 0, warning: 1, info: 2 } as const;
  const shown = issues.filter((i) => showInfo || i.level !== 'info').sort((a, b) => order[a.level] - order[b.level]);
  for (const i of shown) {
    const tag = i.level === 'error' ? red('ERROR  ') : i.level === 'warning' ? yellow('WARN   ') : dim('INFO   ');
    console.log(`${tag}${bold(i.target)}: ${i.message}`);
  }
}

function statusLabel(s: StateReport['status']) {
  return { empty: '—', started: 'started', thin: 'thin', good: 'good' }[s];
}

function markdownReport(country: Country, states: StateReport[], issues: Issue[]) {
  const eraIds = ERAS.map((e) => e.id);
  const lines: string[] = [];
  lines.push(`# Content status — ${country.name.en}`, '');
  lines.push(`Generated by \`npm run content:report\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`, '');
  lines.push(`Status: **good** ≥ ${COMPLETENESS.thinArtists} artists and ≥ ${COMPLETENESS.thinEras} eras · **thin** below that · **started** < 3 artists · **—** no content.`, '');
  lines.push(`| State | Status | Artists | Cities (used/total) | ${eraIds.map((e) => e.slice(2)).join(' | ')} | Genres | Sig 5/4/3/2/1 | Errors | Warnings |`);
  lines.push(`|---|---|---|---|${eraIds.map(() => ':-:').join('|')}|---|---|---|---|`);
  const sorted = [...states].sort((a, b) => b.artists - a.artists || a.name.localeCompare(b.name));
  for (const s of sorted) {
    const eraCells = eraIds.map((e) => (s.erasCovered.includes(e) ? '●' : '·'));
    const sig = [5, 4, 3, 2, 1].map((k) => s.significance[k as 1]).join('/');
    lines.push(`| ${s.name} (${s.code}) | ${statusLabel(s.status)} | ${s.artists} | ${s.citiesWithArtists}/${s.citiesTotal} | ${eraCells.join(' | ')} | ${s.genresCovered.join(', ') || '—'} | ${s.artists ? sig : '—'} | ${s.errors || ''} | ${s.warnings || ''} |`);
  }
  const started = sorted.filter((s) => s.artists > 0);
  lines.push('', '## Gaps in states with content', '');
  for (const s of started) {
    lines.push(`- **${s.name}** — missing eras: ${s.erasMissing.join(', ') || 'none'}; genres not present: ${s.genresMissing.join(', ') || 'none'}`);
  }
  const notable = issues.filter((i) => i.level !== 'info');
  lines.push('', `## Issues (${notable.length})`, '');
  if (!notable.length) lines.push('None.');
  for (const i of notable) lines.push(`- ${i.level.toUpperCase()} — \`${i.target}\`: ${i.message}`);
  const infos = issues.filter((i) => i.level === 'info');
  lines.push('', `## Notes (${infos.length})`, '', 'Intentional exceptions allowed by the guidelines, listed for review.', '');
  for (const i of infos) lines.push(`- \`${i.target}\`: ${i.message}`);
  return lines.join('\n') + '\n';
}

export async function main(args: string[]) {
  const mode = args.includes('--report') ? 'report' : 'validate';
  const showInfo = args.includes('--info') || mode === 'report';
  let errors = 0;

  for (const country of Object.values(COUNTRIES)) {
    const result = validateCountry(country, { genres: GENRES, eras: ERAS, regionContains: regionContainsFor(country) });
    const { issues, states, totals } = result;
    const count = (l: Issue['level']) => issues.filter((i) => i.level === l).length;
    errors += count('error');

    console.log(bold(`\n${country.name.en} — ${totals.artists} artists, ${totals.cities} cities, ${totals.statesWithContent}/${country.regions.length} states with content`));

    if (mode === 'report') {
      const rows = states
        .filter((s) => s.artists > 0 || s.hasContent)
        .sort((a, b) => b.artists - a.artists)
        .map((s) => ({
          state: `${s.code} ${s.name}`,
          status: statusLabel(s.status),
          artists: s.artists,
          cities: `${s.citiesWithArtists}/${s.citiesTotal}`,
          eras: `${s.erasCovered.length}/${ERAS.length}`,
          'missing eras': s.erasMissing.map((e) => e.slice(2)).join(' ') || '—',
          genres: `${s.genresCovered.length}/${GENRES.length}`,
          'sig 5/4/3/2/1': [5, 4, 3, 2, 1].map((k) => s.significance[k as 1]).join('/'),
          issues: s.errors + s.warnings || '',
        }));
      console.table(rows);
      const empty = states.filter((s) => s.status === 'empty').map((s) => s.code);
      console.log(dim(`No content yet (${empty.length}): ${empty.join(' ')}`));
      mkdirSync('reports', { recursive: true });
      const file = `reports/content-status-${country.id}.md`;
      writeFileSync(file, markdownReport(country, states, issues));
      console.log(dim(`Full report → ${file}`));
    }

    printIssues(issues, showInfo);
    const summary = `${count('error')} errors, ${count('warning')} warnings, ${count('info')} notes`;
    console.log(count('error') ? red(summary) : count('warning') ? yellow(summary) : green(summary));
  }
  return errors;
}
